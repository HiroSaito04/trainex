import {COMMAND_TYPES,HARDWARE_CONTROL_IDS} from '@trainex/contracts';
export const CONTROL_COMMANDS=Object.freeze({
 [HARDWARE_CONTROL_IDS.MASTER_HANDLE]:COMMAND_TYPES.MASTER_HANDLE_SET,
 [HARDWARE_CONTROL_IDS.EMERGENCY_BRAKE]:COMMAND_TYPES.EMERGENCY_BRAKE_ACTIVATE,
 [HARDWARE_CONTROL_IDS.EMERGENCY_BRAKE_RELEASE]:COMMAND_TYPES.EMERGENCY_BRAKE_RELEASE,
 [HARDWARE_CONTROL_IDS.VIGILANCE_ACKNOWLEDGE]:COMMAND_TYPES.VIGILANCE_ACKNOWLEDGE,
 [HARDWARE_CONTROL_IDS.HORN]:COMMAND_TYPES.HORN_SET,
 [HARDWARE_CONTROL_IDS.DOORS_OPEN]:COMMAND_TYPES.DOOR_OPEN_REQUEST,
 [HARDWARE_CONTROL_IDS.DOORS_CLOSE]:COMMAND_TYPES.DOOR_CLOSE_REQUEST,
 [HARDWARE_CONTROL_IDS.DOOR_ENABLE_LEFT]:COMMAND_TYPES.DOOR_ENABLE_SET,
 [HARDWARE_CONTROL_IDS.DOOR_ENABLE_RIGHT]:COMMAND_TYPES.DOOR_ENABLE_SET,
});
export function mapControlToCommand(controlId,value){
 const type=CONTROL_COMMANDS[controlId];if(!type)return null;
 if(type===COMMAND_TYPES.MASTER_HANDLE_SET)return {type,value};
 if(type===COMMAND_TYPES.HORN_SET)return {type,value:value===true};
 if(controlId===HARDWARE_CONTROL_IDS.DOOR_ENABLE_LEFT)return {type,value:'LEFT'};
 if(controlId===HARDWARE_CONTROL_IDS.DOOR_ENABLE_RIGHT)return {type,value:'RIGHT'};
 if(type===COMMAND_TYPES.DOOR_OPEN_REQUEST || type===COMMAND_TYPES.DOOR_CLOSE_REQUEST)
   return {type,value:['LEFT','RIGHT','BOTH'].includes(value)?value:null};
 return {type,value:null};
}
